import { validateDiagnosticContextId } from "./workspace-diagnostic-context.mjs";
import { requireAdvisorAssignment } from "./workspace-diagnostic-evidence-review.mjs";
import {
  DIAGNOSTIC_QUESTION_REVISION_REASONS,
  verifyDiagnosticQuestionRevision
} from "./openai-diagnostic-question-reframe.mjs";

export class DiagnosticProtocolGovernanceV2InputError extends Error {}
export class DiagnosticProtocolGovernanceV2StateError extends Error {}

function note(value, label, minimum = 20, maximum = 800) {
  const clean = String(value || "").trim().replace(/\s+/g, " ");
  if (clean.length < minimum || clean.length > maximum) throw new DiagnosticProtocolGovernanceV2InputError(`${label} must be between ${minimum} and ${maximum} characters.`);
  return clean;
}

function publicQuestion(question) {
  return Object.freeze({ ...question, mechanismIds: Object.freeze([...(question.mechanismIds || [])]) });
}

export function validateSponsorProtocolReviewV2(value, sourceQuestions) {
  if (!value || typeof value !== "object" || Array.isArray(value)
    || Object.keys(value).sort().join(",") !== "approvalNote,diagnosticId,questionReviews,questions") {
    throw new DiagnosticProtocolGovernanceV2InputError("Only the diagnostic, governed question reviews, questions, and approval note are accepted.");
  }
  const diagnosticId = validateDiagnosticContextId(value.diagnosticId);
  if (!Array.isArray(sourceQuestions) || sourceQuestions.length !== 18) throw new DiagnosticProtocolGovernanceV2StateError("The steward must prepare the complete 18-question protocol before sponsor review.");
  if (!Array.isArray(value.questionReviews) || value.questionReviews.length !== sourceQuestions.length) throw new DiagnosticProtocolGovernanceV2InputError("Review every governed question before approving the protocol.");
  if (!Array.isArray(value.questions) || value.questions.length !== sourceQuestions.length) throw new DiagnosticProtocolGovernanceV2InputError("The sponsor review must preserve all 18 governed questions.");
  const questions = sourceQuestions.map((source, index) => {
    const review = value.questionReviews[index];
    if (!review || Object.keys(review).sort().join(",") !== "originalQuestion,revisions,status,templateId") throw new DiagnosticProtocolGovernanceV2InputError(`Question ${index + 1} has an invalid review record.`);
    if (review.templateId !== source.templateId || review.originalQuestion !== source.questionText || review.status !== "approved") throw new DiagnosticProtocolGovernanceV2InputError(`Question ${index + 1} is not approved against the steward-prepared protocol.`);
    if (!Array.isArray(review.revisions) || review.revisions.length > 3) throw new DiagnosticProtocolGovernanceV2InputError(`Question ${index + 1} has too many revision attempts.`);
    let priorQuestion = review.originalQuestion;
    for (const revision of review.revisions) {
      if (!revision || Object.keys(revision).sort().join(",") !== "questionText,reason,token"
        || !DIAGNOSTIC_QUESTION_REVISION_REASONS.includes(revision.reason)) throw new DiagnosticProtocolGovernanceV2InputError(`Question ${index + 1} has an invalid governed revision.`);
      if (!verifyDiagnosticQuestionRevision({ diagnosticId, templateId: review.templateId, reason: revision.reason, priorQuestion, questionText: revision.questionText }, revision.token)) throw new DiagnosticProtocolGovernanceV2InputError(`Question ${index + 1} revision was not generated by the governed service.`);
      priorQuestion = revision.questionText;
    }
    const finalText = review.revisions.at(-1)?.questionText || review.originalQuestion;
    const submitted = value.questions[index];
    if (!submitted || Object.keys(submitted).sort().join(",") !== "questionText,templateId"
      || submitted.templateId !== source.templateId || submitted.questionText !== finalText) throw new DiagnosticProtocolGovernanceV2InputError(`Question ${index + 1} does not match its approved review.`);
    return publicQuestion({ ...source, questionText: finalText, contextualizationNote: review.revisions.length ? "Sponsor-requested governed reframing; steward finalization required." : source.contextualizationNote });
  });
  return Object.freeze({ diagnosticId, questions: Object.freeze(questions), questionReviews: Object.freeze(value.questionReviews), approvalNote: note(value.approvalNote, "Sponsor approval note") });
}

function publicState(row) {
  if (!row?.protocol_id) return Object.freeze({ state: "awaiting-steward-protocol", protocol: null, canInvite: false });
  const sponsorApproved = Boolean(row.sponsor_approved_at);
  const stewardFinalized = Boolean(row.steward_finalized_at);
  return Object.freeze({
    state: stewardFinalized ? "finalized" : sponsorApproved ? "awaiting-steward-finalization" : "sponsor-review",
    canInvite: Boolean(row.activation_id && stewardFinalized),
    protocol: Object.freeze({
      protocolId: row.protocol_id,
      protocolVersion: row.protocol_version,
      questionLibraryVersion: row.question_library_version,
      questions: Object.freeze((row.sponsor_reviewed_questions || row.governed_questions).map(publicQuestion)),
      sponsorApprovedAt: row.sponsor_approved_at ? new Date(row.sponsor_approved_at).toISOString() : null,
      stewardFinalizedAt: row.steward_finalized_at ? new Date(row.steward_finalized_at).toISOString() : null
    })
  });
}

const sourceSql = `SELECT protocol.id AS protocol_id,protocol.protocol_version,protocol.question_library_version,
  protocol.governed_questions,protocol.sponsor_reviewed_questions,protocol.sponsor_question_reviews,
  protocol.sponsor_approved_at,protocol.steward_finalized_at,activation.id AS activation_id
  FROM app_shared.diagnostics diagnostic
  LEFT JOIN app_shared.diagnostic_protocols_v2 protocol ON protocol.workspace_id=diagnostic.workspace_id AND protocol.diagnostic_id=diagnostic.id
  LEFT JOIN app_operations.diagnostic_v2_collection_activations activation ON activation.workspace_id=diagnostic.workspace_id AND activation.diagnostic_id=diagnostic.id AND activation.deactivated_at IS NULL
  WHERE diagnostic.id=$1 LIMIT 1`;

export async function getSponsorProtocolReviewV2({ workspaceId, diagnosticId }, connectionString) {
  return withNeonWorkspaceTransaction(workspaceId, async ({ query }) => {
    const result = await query(sourceSql, [validateDiagnosticContextId(diagnosticId)]);
    if (!result.rows[0]) throw new DiagnosticProtocolGovernanceV2StateError("That diagnostic is not available in this workspace.");
    return publicState(result.rows[0]);
  }, connectionString);
}

export async function approveSponsorProtocolReviewV2({ workspaceId, userId, input, now = new Date() }, connectionString) {
  return withNeonWorkspaceTransaction(workspaceId, async ({ query }) => {
    const result = await query(`${sourceSql} FOR UPDATE OF protocol`, [input.diagnosticId]);
    const row = result.rows[0];
    if (!row?.protocol_id) throw new DiagnosticProtocolGovernanceV2StateError("The steward must prepare the protocol before sponsor review.");
    if (row.activation_id || row.steward_finalized_at) throw new DiagnosticProtocolGovernanceV2StateError("The finalized collection protocol can no longer be changed.");
    if (row.sponsor_approved_at) throw new DiagnosticProtocolGovernanceV2StateError("The sponsor protocol review is already complete.");
    const validated = validateSponsorProtocolReviewV2(input, row.governed_questions);
    await query(`UPDATE app_shared.diagnostic_protocols_v2 SET sponsor_reviewed_questions=$3::jsonb,
      sponsor_question_reviews=$4::jsonb,sponsor_approval_note=$5,sponsor_approved_by_clerk_user_id=$6,
      sponsor_approved_at=$7 WHERE diagnostic_id=$1 AND id=$2`,
      [validated.diagnosticId,row.protocol_id,JSON.stringify(validated.questions),JSON.stringify(validated.questionReviews),validated.approvalNote,userId,now]);
    await query(`INSERT INTO app_operations.audit_events (workspace_id,actor_clerk_user_id,action,target_type,target_id,metadata)
      VALUES ($1,$2,'diagnostic.protocol-v2-sponsor-approved','diagnostic',$3,$4::jsonb)`,
      [workspaceId,userId,validated.diagnosticId,JSON.stringify({protocolId:row.protocol_id,questionCount:validated.questions.length,revisionCount:validated.questionReviews.reduce((sum,item)=>sum+item.revisions.length,0)})]);
    const updated = await query(sourceSql, [validated.diagnosticId]);
    return publicState(updated.rows[0]);
  }, connectionString);
}

export function validateStewardProtocolFinalizationV2(value) {
  if (!value || typeof value !== "object" || Array.isArray(value) || Object.keys(value).sort().join(",") !== "approvalNote,diagnosticId") throw new DiagnosticProtocolGovernanceV2InputError("Only the diagnostic and finalization note are accepted.");
  return Object.freeze({ diagnosticId: validateDiagnosticContextId(value.diagnosticId), approvalNote: note(value.approvalNote, "Steward finalization note", 40, 1000) });
}

export async function finalizeStewardProtocolV2({ workspaceId, userId, input, now = new Date() }, connectionString) {
  return withNeonWorkspaceTransaction(workspaceId, async ({ query }) => {
    await requireAdvisorAssignment(query, { diagnosticId: input.diagnosticId, userId, now });
    const result = await query(`${sourceSql} FOR UPDATE OF protocol`, [input.diagnosticId]);
    const row = result.rows[0];
    if (!row?.sponsor_approved_at || !row.sponsor_reviewed_questions) throw new DiagnosticProtocolGovernanceV2StateError("Sponsor approval is required before steward finalization.");
    if (row.activation_id || row.steward_finalized_at) throw new DiagnosticProtocolGovernanceV2StateError("The protocol is already finalized or active.");
    await query(`UPDATE app_shared.diagnostic_protocols_v2 SET governed_questions=sponsor_reviewed_questions,
      steward_finalized_by_clerk_user_id=$3,steward_finalized_at=$4 WHERE diagnostic_id=$1 AND id=$2`,
      [input.diagnosticId,row.protocol_id,userId,now]);
    await query(`INSERT INTO app_operations.audit_events (workspace_id,actor_clerk_user_id,action,target_type,target_id,metadata)
      VALUES ($1,$2,'diagnostic.protocol-v2-steward-finalized','diagnostic',$3,$4::jsonb)`,
      [workspaceId,userId,input.diagnosticId,JSON.stringify({protocolId:row.protocol_id,approvalNote:input.approvalNote,questionCount:row.sponsor_reviewed_questions.length})]);
    const updated = await query(sourceSql, [input.diagnosticId]);
    return publicState(updated.rows[0]);
  }, connectionString);
}

export const sponsorProtocolGovernanceV2Policy = Object.freeze({ requiredQuestionCount: 18, sameQuestionSetForSponsorStewardAndParticipants: true, sponsorFreeformEditingPermitted: false, stewardFinalizationRequired: true, revisionReasons: DIAGNOSTIC_QUESTION_REVISION_REASONS });
